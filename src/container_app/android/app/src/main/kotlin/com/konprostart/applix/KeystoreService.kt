package com.konprostart.applix

import android.content.Context
import android.util.Log
import java.io.File
import java.io.FileInputStream
import java.io.FileOutputStream
import java.security.KeyPairGenerator
import java.security.KeyStore
import java.security.MessageDigest
import java.security.PrivateKey
import java.security.SecureRandom
import java.security.cert.X509Certificate
import java.util.Calendar

/**
 * The stable master key of Applix.
 *
 * Every app that Applix generates is signed with this one key, so an update
 * of a generated app always has the same signature and Android accepts it.
 *
 * Why a file and not the AndroidKeyStore:
 *
 *  - A key in the AndroidKeyStore belongs to the (hardware backed) keystore
 *    of the *container* app. It is invalidated when the container is
 *    reinstalled with a different signature, when the user clears the app
 *    data or after a device restore. When that happens a *new* key was
 *    generated and every app built afterwards was signed with a different
 *    key than before - exactly the "signed with a different key" error.
 *  - The master key lives in the private storage of the app. It survives
 *    every update, it is never regenerated by accident, and the user can
 *    export and import it (Settings → Signing Key) so a new phone or a
 *    restored backup can keep updating the existing apps.
 */
object KeystoreService {
    private const val TAG = "Applix"

    /** The alias of the key inside the keystore file. */
    const val MASTER_ALIAS = "applix"

    /** The password of the keystore file. The file itself lives in the
     *  private storage of the app - that is what actually protects it. */
    private const val STORE_PASSWORD = "applix-master-key"

    private const val KEY_DIR = "keys"
    private const val KEY_FILE = "applix_master.p12"
    private const val KEY_TYPE = "PKCS12"

    /** Where the master key is stored. */
    fun masterKeyFile(context: Context): File {
        val dir = File(context.filesDir, KEY_DIR)
        if (!dir.exists()) dir.mkdirs()
        return File(dir, KEY_FILE)
    }

    /** True when a master key exists. */
    fun keyExists(context: Context): Boolean = masterKeyFile(context).exists()

    /**
     * Loads the master key, creating it exactly once if it does not exist yet.
     * An existing key is never replaced silently.
     */
    @Synchronized
    fun loadOrCreate(context: Context): KeyStore {
        val file = masterKeyFile(context)
        val store = KeyStore.getInstance(KEY_TYPE)
        if (file.exists() && file.length() > 0) {
            try {
                FileInputStream(file).use { store.load(it, STORE_PASSWORD.toCharArray()) }
                if (store.containsAlias(MASTER_ALIAS)) {
                    Log.i(TAG, "Master signing key loaded")
                    return store
                }
                Log.w(TAG, "Master key file has no key - recreating")
            } catch (e: Exception) {
                Log.w(TAG, "Master key could not be read (${e.message}) - recreating")
            }
        }
        return create(context)
    }

    /** Generates a new master key and stores it. */
    @Synchronized
    fun create(context: Context): KeyStore {
        val file = masterKeyFile(context)
        val generator = KeyPairGenerator.getInstance("RSA")
        generator.initialize(2048, SecureRandom())
        val keyPair = generator.generateKeyPair()

        val validityEnd = Calendar.getInstance().apply { add(Calendar.YEAR, 25) }
        val cert = SelfSignedCert.create(
            keyPair,
            "CN=Applix/O=Konprostart/C=NL",
            Calendar.getInstance().time,
            validityEnd.time
        )

        val store = KeyStore.getInstance(KEY_TYPE)
        store.load(null, STORE_PASSWORD.toCharArray())
        store.setKeyEntry(
            MASTER_ALIAS,
            keyPair.private,
            STORE_PASSWORD.toCharArray(),
            arrayOf(cert)
        )
        FileOutputStream(file).use { store.store(it, STORE_PASSWORD.toCharArray()) }

        // Sanity check: the certificate has to be usable for signing, otherwise
        // every build would fail with an opaque error.
        val stored = store.getCertificate(MASTER_ALIAS) as X509Certificate
        check(stored.publicKey == keyPair.public) { "The master certificate does not match the key" }
        Log.i(TAG, "New master signing key created at ${file.absolutePath} (${KeystoreService.digest(stored.encoded)})")
        return store
    }

    /** The private key used for signing. */
    fun privateKey(context: Context): PrivateKey =
        loadOrCreate(context).getKey(MASTER_ALIAS, STORE_PASSWORD.toCharArray()) as PrivateKey

    /** The certificate of the master key. */
    fun certificate(context: Context): X509Certificate =
        loadOrCreate(context).getCertificate(MASTER_ALIAS) as X509Certificate

    /** SHA-256 fingerprint of the master certificate - the identity that every
     *  app generated by Applix shares. */
    fun fingerprint(context: Context): String {
        val cert = try {
            certificate(context)
        } catch (e: Exception) {
            return ""
        }
        return digest(cert.encoded)
    }

    /** SHA-256 of a certificate, uppercase hex with colons. */
    fun digest(certBytes: ByteArray): String =
        MessageDigest.getInstance("SHA-256").digest(certBytes)
            .joinToString(":") { "%02X".format(it) }

    /**
     * Imports a master key from a keystore file (Settings → Signing Key →
     * Import). The imported key replaces the current one, so the apps built
     * with it can be updated again.
     */
    fun importKey(context: Context, source: File): String {
        return try {
            val store = KeyStore.getInstance(KEY_TYPE)
            FileInputStream(source).use { store.load(it, STORE_PASSWORD.toCharArray()) }
            if (!store.containsAlias(MASTER_ALIAS)) {
                return "That file is not an Applix master key"
            }
            val file = masterKeyFile(context)
            FileOutputStream(file).use { store.store(it, STORE_PASSWORD.toCharArray()) }
            "Master key imported - rebuild your apps so they use it"
        } catch (e: Exception) {
            "Could not import the key: ${e.message}"
        }
    }

    /** Deletes the master key. Existing apps can no longer be updated. */
    fun deleteKey(context: Context) {
        val file = masterKeyFile(context)
        if (file.exists()) {
            file.delete()
            Log.w(TAG, "Master signing key deleted")
        }
    }
}
